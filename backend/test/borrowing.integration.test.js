const test = require("node:test");
const assert = require("node:assert/strict");
const { once } = require("node:events");
const mongoose = require("mongoose");
const jwt = require("jsonwebtoken");
const readConfig = require("../src/config/env");
const connectDB = require("../src/config/db");
const createApp = require("../src/app");
const User = require("../src/models/userModel");
const Book = require("../src/models/bookModel");
const Borrowing = require("../src/models/borrowingModel");

// DO NOT load developer backend/.env for integration test runs.
// Require an explicit TEST_MONGO_URI or fallback to local test database.
const testMongoUri = process.env.TEST_MONGO_URI || "mongodb://127.0.0.1:27017/library_borrowing_integration_test";

// Safeguard: verify database name contains "test" to protect shared/production databases.
const getDatabaseName = (uri) => {
    try {
        const normalized = uri.replace("mongodb+srv://", "http://").replace("mongodb://", "http://");
        const parsed = new URL(normalized);
        return parsed.pathname.replace(/^\//, "").split("?")[0];
    } catch {
        return "";
    }
};

const dbName = getDatabaseName(testMongoUri);
if (!dbName.toLowerCase().includes("test")) {
    throw new Error(
        `Refusing to run integration tests on non-test database: '${dbName}'. ` +
        `TEST_MONGO_URI must target a database name containing 'test'.`
    );
}

const env = {
    MONGO_URI: testMongoUri,
    JWT_SECRET: "x".repeat(32),
    FRONTEND_URL: "http://127.0.0.1:5173"
};

const adminToken = jwt.sign(
    { id: "60d5ecb8b5c9c61234567801", email: "admin@library.org", role: "Admin" },
    env.JWT_SECRET,
    { expiresIn: "1h" }
);

test("MongoDB Transactional Borrowing Integration Suite", async (t) => {
    let server;

    try {
        await connectDB(testMongoUri);
    } catch (err) {
        t.skip("MongoDB connection unavailable for transactional integration tests: " + err.message);
        return;
    }

    server = createApp(readConfig(env)).listen(0);
    await once(server, "listening");
    const port = server.address().port;
    const baseUrl = `http://127.0.0.1:${port}/api/borrowings`;

    // Ensure database indexes including partial unique index are built
    await Promise.all([User.syncIndexes(), Book.syncIndexes(), Borrowing.syncIndexes()]);

    // Scoped cleanup: only clean up test records generated by this suite
    const cleanCollections = async () => {
        const testUsers = await User.find({ email: /@integration\.test$/ }, "_id");
        const testBooks = await Book.find({ ISBN: /^TEST-/ }, "_id");
        const userIds = testUsers.map((u) => u._id);
        const bookIds = testBooks.map((b) => b._id);

        await Promise.all([
            Borrowing.deleteMany({
                $or: [{ userId: { $in: userIds } }, { bookId: { $in: bookIds } }]
            }),
            User.deleteMany({ email: /@integration\.test$/ }),
            Book.deleteMany({ ISBN: /^TEST-/ })
        ]);
    };

    await cleanCollections();

    t.after(async () => {
        await cleanCollections();
        if (server) {
            await new Promise((resolve) => server.close(resolve));
        }
        await mongoose.disconnect();
    });

    await t.test("Rollback: Injected Borrowing.create failure rolls back decremented book stock", async () => {
        const testUser = await User.create({
            name: "Rollback User",
            email: "rollback@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const testBook = await Book.create({
            title: "Transaction Test Book",
            author: "Author T",
            ISBN: "TEST-ISBN-ROLLBACK-01",
            category: "Database",
            totalCopies: 5,
            availableCopies: 2
        });

        // Intercept Borrowing.create to simulate runtime error during transaction
        const originalCreate = Borrowing.create;
        Borrowing.create = async () => {
            throw new Error("Simulated database failure during loan creation");
        };

        try {
            const dueDate = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString();
            const res = await fetch(baseUrl, {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    Authorization: `Bearer ${adminToken}`
                },
                body: JSON.stringify({
                    userId: testUser._id.toString(),
                    bookId: testBook._id.toString(),
                    dueDate
                })
            });

            // Must fail because transaction failed
            assert.equal(res.status, 500);

            // Verify Book stock was NOT decremented (rolled back to original 2)
            const bookAfter = await Book.findById(testBook._id);
            assert.equal(
                bookAfter.availableCopies,
                2,
                "availableCopies must remain 2 after aborted transaction"
            );

            // Verify no borrowing records were persisted
            const loans = await Borrowing.find({ bookId: testBook._id });
            assert.equal(loans.length, 0, "No borrowing record should exist");
        } finally {
            Borrowing.create = originalCreate;
        }
    });

    await t.test("Race condition: Concurrent duplicate issue requests enforce unique active-loan constraint and preserve stock", async () => {
        const testUser = await User.create({
            name: "Race Borrower",
            email: "race@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const testBook = await Book.create({
            title: "Concurrency Book",
            author: "Author C",
            ISBN: "TEST-ISBN-CONCUR-01",
            category: "Concurrency",
            totalCopies: 5,
            availableCopies: 5
        });

        const dueDate = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString();
        const payload = JSON.stringify({
            userId: testUser._id.toString(),
            bookId: testBook._id.toString(),
            dueDate
        });

        // Fire two concurrent requests for the exact same user and book
        const [res1, res2] = await Promise.all([
            fetch(baseUrl, {
                method: "POST",
                headers: { "Content-Type": "application/json", Authorization: `Bearer ${adminToken}` },
                body: payload
            }),
            fetch(baseUrl, {
                method: "POST",
                headers: { "Content-Type": "application/json", Authorization: `Bearer ${adminToken}` },
                body: payload
            })
        ]);

        const statuses = [res1.status, res2.status].sort();
        // Exactly one request must succeed with 201, and one must be rejected with 409
        assert.deepEqual(statuses, [201, 409], "One request must succeed (201) and one must conflict (409)");

        // Verify stock was decremented exactly once (from 5 to 4)
        const bookAfter = await Book.findById(testBook._id);
        assert.equal(bookAfter.availableCopies, 4, "availableCopies must be exactly 4");

        // Verify exactly one borrowing record exists
        const loans = await Borrowing.find({ userId: testUser._id, bookId: testBook._id, status: "issued" });
        assert.equal(loans.length, 1, "Exactly one active loan should exist");
    });

    await t.test("Race condition: Contention for the last available copy allows only one winner", async () => {
        const userA = await User.create({
            name: "User A",
            email: "usera@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const userB = await User.create({
            name: "User B",
            email: "userb@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const lastCopyBook = await Book.create({
            title: "Last Copy Book",
            author: "Author L",
            ISBN: "TEST-ISBN-LASTCOPY-01",
            category: "Contention",
            totalCopies: 1,
            availableCopies: 1 // Only 1 copy available
        });

        const dueDate = new Date(Date.now() + 7 * 24 * 60 * 60 * 1000).toISOString();

        // Two different users contend for the last copy concurrently
        const [resA, resB] = await Promise.all([
            fetch(baseUrl, {
                method: "POST",
                headers: { "Content-Type": "application/json", Authorization: `Bearer ${adminToken}` },
                body: JSON.stringify({ userId: userA._id.toString(), bookId: lastCopyBook._id.toString(), dueDate })
            }),
            fetch(baseUrl, {
                method: "POST",
                headers: { "Content-Type": "application/json", Authorization: `Bearer ${adminToken}` },
                body: JSON.stringify({ userId: userB._id.toString(), bookId: lastCopyBook._id.toString(), dueDate })
            })
        ]);

        const statuses = [resA.status, resB.status].sort();
        assert.deepEqual(statuses, [201, 409], "Exactly one user gets the last copy, the other gets 409");

        const bookAfter = await Book.findById(lastCopyBook._id);
        assert.equal(bookAfter.availableCopies, 0, "availableCopies must be 0 and never negative");
    });

    await t.test("Return: Concurrent duplicate return requests allow only one winner and restore stock exactly once", async () => {
        const retUser = await User.create({
            name: "Return Borrower",
            email: "retborrower@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const retBook = await Book.create({
            title: "Return Concurrency Book",
            author: "Author R",
            ISBN: "TEST-ISBN-RETCON-01",
            category: "Concurrency",
            totalCopies: 5,
            availableCopies: 3
        });

        const loan = await Borrowing.create({
            userId: retUser._id,
            bookId: retBook._id,
            dueDate: new Date(Date.now() + 86400000),
            status: "issued",
            issueDate: new Date()
        });

        const returnUrl = `${baseUrl}/${loan._id}/return`;

        // Two concurrent return requests for the exact same active loan
        const [res1, res2] = await Promise.all([
            fetch(returnUrl, {
                method: "PATCH",
                headers: { Authorization: `Bearer ${adminToken}` }
            }),
            fetch(returnUrl, {
                method: "PATCH",
                headers: { Authorization: `Bearer ${adminToken}` }
            })
        ]);

        const statuses = [res1.status, res2.status].sort();
        assert.deepEqual(statuses, [200, 409], "Exactly one return request must succeed (200) and one must conflict (409)");

        // Stock restored from 3 to 4 (exactly once)
        const bookAfter = await Book.findById(retBook._id);
        assert.equal(bookAfter.availableCopies, 4, "availableCopies must increment exactly once to 4");

        // Loan record updated to returned
        const loanAfter = await Borrowing.findById(loan._id);
        assert.equal(loanAfter.status, "returned");
        assert.ok(loanAfter.returnDate instanceof Date);
    });

    await t.test("Return Rollback: Simulated stock update failure rolls back borrowing return status", async () => {
        const retUser = await User.create({
            name: "Return Rollback User",
            email: "retrollback@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const retBook = await Book.create({
            title: "Return Rollback Book",
            author: "Author RR",
            ISBN: "TEST-ISBN-RETROLL-01",
            category: "Rollback",
            totalCopies: 5,
            availableCopies: 2
        });

        const loan = await Borrowing.create({
            userId: retUser._id,
            bookId: retBook._id,
            dueDate: new Date(Date.now() + 86400000),
            status: "issued",
            issueDate: new Date()
        });

        const originalBookFindByIdAndUpdate = Book.findByIdAndUpdate;
        Book.findByIdAndUpdate = async () => {
            throw new Error("Simulated database failure during stock increment");
        };

        try {
            const returnUrl = `${baseUrl}/${loan._id}/return`;
            const res = await fetch(returnUrl, {
                method: "PATCH",
                headers: { Authorization: `Bearer ${adminToken}` }
            });

            assert.equal(res.status, 500);

            // Verify borrowing record status was rolled back to issued
            const loanAfter = await Borrowing.findById(loan._id);
            assert.equal(loanAfter.status, "issued");
            assert.equal(loanAfter.returnDate, null);

            // Verify stock remained unchanged
            const bookAfter = await Book.findById(retBook._id);
            assert.equal(bookAfter.availableCopies, 2);
        } finally {
            Book.findByIdAndUpdate = originalBookFindByIdAndUpdate;
        }
    });

    await t.test("GET /api/borrowings: Role and ownership isolation on live database", async () => {
        const userA = await User.create({
            name: "User Isolation A",
            email: "user_iso_a@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const userB = await User.create({
            name: "User Isolation B",
            email: "user_iso_b@integration.test",
            passwordHash: "hashed",
            role: "User"
        });

        const isoBook = await Book.create({
            title: "Isolation Book",
            author: "Author I",
            ISBN: "TEST-ISBN-ISO-01",
            category: "Isolation",
            totalCopies: 5,
            availableCopies: 3
        });

        await Borrowing.create([
            {
                userId: userA._id,
                bookId: isoBook._id,
                dueDate: new Date(Date.now() + 86400000),
                status: "issued",
                issueDate: new Date()
            },
            {
                userId: userB._id,
                bookId: isoBook._id,
                dueDate: new Date(Date.now() + 86400000),
                status: "returned",
                issueDate: new Date(),
                returnDate: new Date()
            }
        ]);

        const userAToken = jwt.sign(
            { id: userA._id.toString(), email: userA.email, role: "User" },
            env.JWT_SECRET,
            { expiresIn: "1h" }
        );

        // 1. Admin sees records for both users
        const resAdmin = await fetch(baseUrl, {
            headers: { Authorization: `Bearer ${adminToken}` }
        });
        assert.equal(resAdmin.status, 200);
        const bodyAdmin = await resAdmin.json();
        const foundA = bodyAdmin.data.some((b) => b.userId === userA._id.toString());
        const foundB = bodyAdmin.data.some((b) => b.userId === userB._id.toString());
        assert.ok(foundA && foundB, "Admin must be able to view borrowing records for all users");

        // 2. User A only sees their own records
        const resUserA = await fetch(baseUrl, {
            headers: { Authorization: `Bearer ${userAToken}` }
        });
        assert.equal(resUserA.status, 200);
        const bodyUserA = await resUserA.json();
        assert.ok(bodyUserA.data.length >= 1);
        assert.ok(bodyUserA.data.every((b) => b.userId === userA._id.toString()));

        // 3. User A attempts to spoof ?userId=userB._id -> still only sees User A records
        const resSpoof = await fetch(`${baseUrl}?userId=${userB._id.toString()}`, {
            headers: { Authorization: `Bearer ${userAToken}` }
        });
        assert.equal(resSpoof.status, 200);
        const bodySpoof = await resSpoof.json();
        assert.ok(bodySpoof.data.every((b) => b.userId === userA._id.toString()));
    });
});
